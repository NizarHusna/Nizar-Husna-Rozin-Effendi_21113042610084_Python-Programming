usia = 20

if usia < 2:
    print("Orang tersebut masih bayi.")
elif usia < 4:
    print("Orang tersebut masih balita.")
elif usia < 13:
    print("Orang tersebut masih anak-anak.")
elif usia < 20:
    print("Orang tersebut adalah remaja.")
elif usia < 65:
    print("Orang tersebut adalah orang dewasa.")
else:
    print("Orang tersebut adalah lansia.")