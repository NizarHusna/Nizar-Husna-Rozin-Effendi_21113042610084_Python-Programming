tempat = ["Tokyo", "Barcelona", "London", "Lauterbrunnen", "Kyoto"]

#Menampilkan urutan yang asli
print("Urutan Asli:")
print(tempat)

#Mengurutkan berdasarkan abjad
print("Urutan Berdasarkan Abjad:")
print(sorted(tempat))

#Membuktikan bahwa urutan asli tidak berubah
print("Urutan Asli:")
print(tempat)

#Mengurutkan secara terbalik berdasarkan abjad
print("Urutan Terbalik Berdasarkan Abjad:")
print(sorted(tempat, reverse=True))

#Membuktikan bahwa urutan asli tidak berubah
print("Urutan Asli:")
print(tempat)